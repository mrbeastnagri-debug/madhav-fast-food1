-- Public website needs read access.
alter table site_settings enable row level security;
alter table categories enable row level security;
alter table menu_items enable row level security;
alter table orders enable row level security;

create policy "public read settings" on site_settings for select using (true);
create policy "public read categories" on categories for select using (true);
create policy "public read menu" on menu_items for select using (true);

-- Customer order creation and status reading.
create policy "public create orders" on orders for insert with check (true);
create policy "public read orders" on orders for select using (true);
create policy "public update orders" on orders for update using (true) with check (true);
create policy "public delete orders" on orders for delete using (true);

-- Owner dashboard writes (password is handled by the site for this simple village deployment).
create policy "public insert menu" on menu_items for insert with check (true);
create policy "public update menu" on menu_items for update using (true) with check (true);
create policy "public delete menu" on menu_items for delete using (true);
create policy "public update settings" on site_settings for update using (true) with check (true);

-- Storage bucket for food images.
insert into storage.buckets (id,name,public) values ('food-images','food-images',true)
on conflict (id) do update set public=true;

create policy "public image upload" on storage.objects for insert with check (bucket_id='food-images');
create policy "public image read" on storage.objects for select using (bucket_id='food-images');
create policy "public image update" on storage.objects for update using (bucket_id='food-images') with check (bucket_id='food-images');
create policy "public image delete" on storage.objects for delete using (bucket_id='food-images');
