-- Madhav Fast Food - Supabase setup
-- Run this entire file in Supabase SQL Editor.

create table if not exists site_settings (
  id bigint primary key,
  restaurant text default 'Madhav Fast Food',
  village text default 'आपका गाँव',
  phone text default '',
  whatsapp text default '',
  delivery numeric default 20,
  min_order numeric default 0
);

create table if not exists categories (
  id bigint generated by default as identity primary key,
  name text not null,
  sort_order int default 0
);

create table if not exists menu_items (
  id bigint generated by default as identity primary key,
  cat bigint references categories(id) on delete set null,
  name text not null,
  price numeric not null default 0,
  desc text default '',
  image_url text,
  emoji text default '🍽️',
  available boolean default true,
  sort_order int default 0
);

create table if not exists orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  name text not null,
  phone text not null,
  village text not null,
  address text not null,
  payment text not null,
  note text default '',
  items jsonb not null,
  subtotal numeric not null,
  delivery numeric default 0,
  total numeric not null,
  status text default 'Order Received'
);

insert into site_settings(id) values (1) on conflict (id) do nothing;

